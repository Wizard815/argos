"""The seam between SQLite and Postgres, tested without a server.

These are the translations the store depends on. A mistake here does not fail
loudly - it silently puts a row in the wrong hourly bucket, or drops a filter -
so they are pinned down one at a time.
"""
import pytest

from src import dialect


# ---------------------------------------------------------------- which database

def test_url_is_empty_when_unset(monkeypatch):
    monkeypatch.delenv("ARGOS_DATABASE_URL", raising=False)
    assert dialect.url() == ""
    assert dialect.is_postgres(dialect.url()) is False


@pytest.mark.parametrize("dsn", ["postgresql://u:p@h/db", "postgres://u:p@h/db"])
def test_postgres_urls_are_recognised(monkeypatch, dsn):
    monkeypatch.setenv("ARGOS_DATABASE_URL", dsn)
    assert dialect.is_postgres(dialect.url()) is True


# ---------------------------------------------------------------- placeholders

def test_placeholders_become_percent_s():
    assert dialect.translate("SELECT * FROM t WHERE a=? AND b=?") == "SELECT * FROM t WHERE a=%s AND b=%s"


def test_a_question_mark_in_a_literal_is_data():
    sql = "SELECT * FROM notes WHERE body LIKE 'why?' AND id=?"
    out = dialect.translate(sql)
    assert "'why?'" in out, "the literal was left alone"
    assert out.endswith("id=%s")


def test_a_percent_in_a_like_pattern_is_escaped():
    # psycopg reads a bare % as the start of a placeholder the moment arguments
    # are passed, so a LIKE '%qwen%' would raise rather than match.
    out = dialect.translate("SELECT * FROM models WHERE name LIKE '%qwen%' AND id=?")
    assert "%%qwen%%" in out
    assert out.endswith("id=%s")


def test_a_doubled_quote_inside_a_literal_survives():
    out = dialect.translate("SELECT * FROM notes WHERE body='it''s ok?' AND id=?")
    assert "'it''s ok?'" in out
    assert out.endswith("id=%s")


# ---------------------------------------------------------------- time buckets

def test_a_time_bucket_truncates_rather_than_rounds():
    # SQLite's CAST truncates; Postgres's CAST rounds. 1.6 seconds into an hour
    # must land in bucket 0, not bucket 1, or every chart is a bucket out.
    out = dialect.translate("SELECT CAST(ts / ? AS INTEGER) * ? AS t FROM gpu_samples")
    assert out == "SELECT floor(ts / %s)::bigint * %s AS t FROM gpu_samples"


def test_the_multi_column_bucket():
    out = dialect.translate("SELECT CAST(hour / 3600 AS INTEGER) * 3600 AS h FROM gpu_hourly")
    assert out == "SELECT floor(hour / 3600)::bigint * 3600 AS h FROM gpu_hourly"


# ---------------------------------------------------------------- upserts

def test_insert_or_ignore_becomes_on_conflict_do_nothing():
    out = dialect.translate("INSERT OR IGNORE INTO requests (a, b) VALUES (?, ?)")
    assert out.upper().startswith("INSERT INTO")
    assert out.upper().endswith("ON CONFLICT DO NOTHING")
    assert "%s" in out


def test_an_existing_on_conflict_is_not_doubled():
    out = dialect.translate("INSERT OR IGNORE INTO t (a) VALUES (?) ON CONFLICT (a) DO NOTHING")
    assert out.upper().count("ON CONFLICT") == 1


# ---------------------------------------------------------------- collation

def test_collate_nocase_is_removed():
    assert dialect.translate("SELECT * FROM m ORDER BY name COLLATE NOCASE") == "SELECT * FROM m ORDER BY name"


# ---------------------------------------------------------------- the schema

def test_the_schema_uses_identity_columns():
    out = dialect.schema_for_postgres("CREATE TABLE t (id INTEGER PRIMARY KEY AUTOINCREMENT, a TEXT);")
    assert "GENERATED BY DEFAULT AS IDENTITY" in out
    assert "AUTOINCREMENT" not in out


def test_the_schema_widens_real_and_blob():
    out = dialect.schema_for_postgres(
        "CREATE TABLE t (id INTEGER PRIMARY KEY AUTOINCREMENT, ts REAL NOT NULL, vec BLOB, n INTEGER);")
    assert "ts double precision" in out
    assert "vec bytea" in out
    assert "n bigint" in out


def test_the_schema_leaves_text_check_and_unique_alone():
    src = ("CREATE TABLE IF NOT EXISTS t (kind TEXT NOT NULL CHECK (kind IN ('a','b')), "
           "name TEXT, UNIQUE (kind, name));")
    out = dialect.schema_for_postgres(src)
    assert "CHECK (kind IN ('a','b'))" in out
    assert "UNIQUE (kind, name)" in out
    assert "CREATE TABLE IF NOT EXISTS" in out


def test_the_real_schema_translates_cleanly():
    import re

    from src.db import SCHEMA

    out = dialect.schema_for_postgres(SCHEMA)
    assert "AUTOINCREMENT" not in out
    assert not re.search(r"\bREAL\b", out)
    assert not re.search(r"\bINTEGER\b", out)
    assert "bytea" in out, "the embedding vector kept its type"
    # the composite key on the hourly rollup is valid Postgres as written
    assert "PRIMARY KEY (hour, gpu)" in out


# ---------------------------------------------------------------- counts

def test_statement_count_counts_the_schema():
    assert dialect.statement_count("SELECT 1; SELECT 2;") == 2
    assert dialect.statement_count("  ;  ") == 0
