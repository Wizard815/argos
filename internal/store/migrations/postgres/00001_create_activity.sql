CREATE TABLE IF NOT EXISTS activity (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ts_created BIGINT NOT NULL,
    model_id TEXT NOT NULL,
    req_path TEXT NOT NULL DEFAULT '',
    resp_content_type TEXT NOT NULL DEFAULT '',
    resp_status_code BIGINT NOT NULL DEFAULT 0,
    cache_tokens BIGINT NOT NULL DEFAULT 0,
    draft_tokens BIGINT NOT NULL DEFAULT 0,
    draft_acc_tokens BIGINT NOT NULL DEFAULT 0,
    input_tokens BIGINT NOT NULL DEFAULT 0,
    output_tokens BIGINT NOT NULL DEFAULT 0,
    prompt_per_second DOUBLE PRECISION NOT NULL DEFAULT 0,
    tokens_per_second DOUBLE PRECISION NOT NULL DEFAULT 0,
    duration_ms BIGINT NOT NULL DEFAULT 0,
    error_msg TEXT NOT NULL DEFAULT '',
    metadata_json TEXT NOT NULL DEFAULT ''
);

CREATE INDEX IF NOT EXISTS idx_activity_created_id
    ON activity (ts_created DESC, id DESC);

CREATE INDEX IF NOT EXISTS idx_activity_model_created_id
    ON activity (model_id, ts_created DESC, id DESC);

